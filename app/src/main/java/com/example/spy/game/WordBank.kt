    val categories: List<String> = pairs.map { it.category }.distinct()

    /** Случайная пара из всего банка. */
    fun randomPair(random: Random = Random.Default): WordPair = pairs.random(random)

    /** Случайная пара из выбранных категорий (если список пуст — из всех). */
    fun randomPair(fromCategories: Set<String>, random: Random = Random.Default): WordPair {
        if (fromCategories.isEmpty()) return randomPair(random)
        val filtered = pairs.filter { it.category in fromCategories }
        return if (filtered.isEmpty()) randomPair(random) else filtered.random(random)
    }

    /**
     * Случайная пара, исключая уже сыгранные [exclude] — чтобы слова не повторялись,
     * пока банк не исчерпан (иначе игроки выучивают пары и начинается мета-игра).
     * Возвращает null, если все доступные пары уже использованы (вызывающий сбрасывает историю).
     */
    fun randomPairExcluding(
        fromCategories: Set<String>,
        exclude: Set<WordPair>,
        random: Random = Random.Default,
    ): WordPair? {
        val base = if (fromCategories.isEmpty()) pairs
        else pairs.filter { it.category in fromCategories }.ifEmpty { pairs }
        val fresh = base.filter { it !in exclude }
        return if (fresh.isEmpty()) null else fresh.random(random)
    }

    /**
     * N слов из указанной категории — набор кандидатов для угадывания слова мирных.
     * Обязательно включает [mustInclude] (слово мирных) и, если задано, [alsoInclude]
     * (слово шпиона — как «приманку»). Список у всех игроков одинаковый: и мирный,
     * и шпион видят в нём своё слово, поэтому список никого не выдаёт.
     */
    fun wordsFromCategory(
        category: String,
        count: Int = 6,
        mustInclude: String,
        alsoInclude: String? = null,
        random: Random = Random.Default,
    ): List<String> {
        val required = listOfNotNull(mustInclude, alsoInclude).distinct()
        val pool = pairs
            .filter { it.category == category }
            .flatMap { listOf(it.civilian, it.spy) }
            .distinct()
            .filter { it !in required }
        val extras = pool.shuffled(random).take((count - required.size).coerceAtLeast(0))
        return (extras + required).shuffled(random)
    }
